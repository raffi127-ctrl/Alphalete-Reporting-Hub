"""Write the approved applicant replies out as markdown.

The editor artifact is the working surface; this is the copy that lives in
the repo, so a session with no artifact access still has every approved
reply, the rule behind it, and what each one is waiting on.

Reads editor.html (the card definitions) and edits/ (what was typed into
the editor and saved). A saved row only holds what someone typed, so an
empty slot falls back to the card's own text.

    python3 -m automations.sms_audit.reply_sheets.build_doc
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent.parent / "resources" / "recruiting-context" / "ai-reply-templates.md"


def load():
    html = (HERE / "editor.html").read_text()
    cards = json.loads(re.search(r'id="seed">(.*?)</script>', html, re.S).group(1))
    saved = {}
    for f in sorted((HERE / "edits").glob("*.json")):
        d = json.loads(f.read_text())
        saved[f.stem] = d.get("data", d)
    return cards, saved


def replies(card, saved):
    seed = [(v or "").strip() for v in card.get("variants", [])]
    row = saved.get(card["id"], {})
    out = []
    for k in range(5):
        typed = (row.get("v%d" % (k + 1)) or "").strip()
        out.append(typed or (seed[k] if k < len(seed) else ""))
    return [v for v in out if v]


# Confirmed present in AppStream's SMS merge-variable list. Everything
# else a reply uses has to be built before that reply can ship.
LIVE = {
    "applicantFirstName", "applicantLastName", "applicantName",
    "adPostingTitle", "jobBoard", "officeName", "officeCity", "officeState",
    "officeZip", "currentInterviewDay", "nextInterviewDay", "ssLink",
    "zoomlink1",
    # older spellings still sitting in saved rows; same fields underneath
    "companyName", "roleTitle", "jobboard", "videoIview",
}


def gaps(card, saved):
    """Shortcodes this card uses that AppStream cannot fill yet."""
    used = set()
    for r in replies(card, saved):
        used |= set(re.findall(r"\{([A-Za-z][A-Za-z0-9]*)\}", r))
    return sorted(u for u in used if u not in LIVE)


def main():
    cards, saved = load()
    qs = [c for c in cards if c.get("kind") not in ("info", "asks")]
    qs.sort(key=lambda c: c.get("n", 99))
    sheets = {c["id"]: c for c in cards if c.get("kind") in ("info", "asks")}

    L = []
    w = L.append
    w("# Approved applicant replies")
    w("")
    w("Every reply the ApplicantStream AI sends when an applicant asks us "
      "something. %d questions, signed off by Megan one card at a time "
      "between 2026-10-26 and 2026-11-03." % len(qs))
    w("")
    w("Generated by `automations/sms_audit/reply_sheets/build_doc.py` from "
      "`editor.html` + `edits/`. Edit there, not here.")
    w("")
    w("**The live pages**")
    w("")
    w("| | Who it is for | Link |")
    w("|---|---|---|")
    w("| Editor | Megan — review and edit, private | https://claude.ai/artifact/SE9sdkrTUvtVxx92QumsX9 |")
    w("| AI build sheet | eStream / the voice-AI team — shortcodes and status | https://claude.ai/artifact/QqHyfff9tDpzU9C2SRUCKL |")
    w("| Recruiter sheet | human recruiters — blanks to fill in, no shortcodes | https://claude.ai/artifact/EQrUxzky6T3R1DABGD25Th |")
    w("")
    w("The two shared pages do not update themselves. Rebuild them with "
      "`build_ai_sheet.py` and `build_recruiter_sheet.py` after any change, "
      "then publish to the same URLs.")
    w("")
    w("---")
    w("")
    w("## The questions")
    w("")
    w("| # | Question | Asked | Shortcodes still to build |")
    w("|---|---|---|---|")
    for c in qs:
        g = gaps(c, saved)
        w("| %d | %s | %s | %s |"
          % (c["n"], c["q"], c.get("asked", "?"),
             ", ".join("`{%s}`" % x for x in g) or "ready"))
    w("")
    w("---")
    w("")

    for c in qs:
        w("## %d. %s" % (c["n"], c["q"]))
        w("")
        if c.get("asked"):
            w("**Asked %s times** in the week to 2026-09-25, across 11280 / 11580 "
              "/ 23965 / 24065." % c["asked"])
            w("")
        if c.get("share"):
            w("> %s" % c["share"])
            w("")
        for e in c.get("ex", [])[:3]:
            w("- *“%s”*" % e.strip())
        if c.get("ex"):
            w("")
        w("**Replies**")
        w("")
        for i, r in enumerate(replies(c, saved), 1):
            lines = [l for l in r.split("\n") if l.strip()]
            w("%d. %s" % (i, lines[0].strip()))
            for extra in lines[1:]:
                w("   %s" % extra.strip())
            w("")
        if c.get("routing"):
            w("**Routing:** %s — %s" % (c["routing"], c.get("routingWhy", "")))
            w("")
        if c.get("rule"):
            w("**Rules**")
            w("")
            for para in c["rule"].split("\n\n"):
                if para.strip():
                    w("- %s" % para.strip().replace("\n", " "))
            w("")
        g = gaps(c, saved)
        w("**Shortcodes still to build:** %s"
          % (", ".join("`{%s}`" % x for x in g) if g else "none \u2014 this one can ship"))
        w("")
        if c.get("build"):
            w("**Build notes:** %s" % c["build"])
            w("")
            for s in c.get("buildsteps", []):
                w("  - %s" % s)
            if c.get("buildsteps"):
                w("")
        w("---")
        w("")

    for sid in ("copystd", "shortcodes", "icdinfo", "routing", "status_matrix"):
        s = sheets.get(sid)
        if not s:
            continue
        w("## %s" % s["q"])
        w("")
        if s.get("share"):
            w("> %s" % s["share"])
            w("")
        for g in s.get("groups", []):
            w("### %s" % g["h"])
            w("")
            for row in g["rows"]:
                w("- **%s** — %s" % (row[0], row[1].replace("\n\n", " ").replace("\n", " ")))
            w("")
        w("---")
        w("")

    w("## Where this was left, 2026-11-03")
    w("")
    w("- All %d questions approved. Nothing in the editor is waiting on Megan." % len(qs))
    w("- Shortcodes: 13 exist in AppStream today, the rest are in the table "
      "above and have to be built before those replies can ship.")
    w("- `{officePhone}`, `{officeAddress2}` and `{ssTimeSlots}` exist for "
      "EMAIL templates only and cannot be read from an SMS. Card 13 is "
      "blocked entirely on the first of those.")
    w("- `officeAddress1` says \u201c5217 Tennyson Pkwy Suite 100\u201d while "
      "`officeAddress2` says \u201cSte 232\u201d. They contradict each other and "
      "applicants have asked about exactly this. Resolve before any address "
      "reply ships.")
    w("- Four rows on 11280 are set to the wrong routing mode. Escalate STOPS "
      "the AI speaking again: measured 0-15% further AI messages after an "
      "Escalate row, against 47% after Clarify.")
    w("- `output/estream-asks-2026-10-26.md` is drafted and UNSENT, and is now "
      "out of date \u2014 several cards shed their dependencies and new ones "
      "appeared. Regenerate before sending. Megan sends it, not us.")
    w("- 28 of the 51 AppStream escalation rows still have no template. The "
      "busiest untouched one is User Not Interested / Opt Out at 91 a week.")
    w("- A separate session was forked on 2026-10-29 to map these onto the 51 "
      "rows and produce a row-by-row change set. It had not reported back.")
    w("")
    w("### Questions deliberately NOT templated")
    w("")
    w("- **\u201cAny updates? / Am I still being considered?\u201d** \u2014 Escalate, no "
      "template. The answer is a judgement about one person and a recruiter "
      "owns it case by case (Megan, 2026-10-30). A generic reply is either a "
      "false promise or a rejection by accident.")
    w("- **Running late, still coming** \u2014 needs a held slot and a "
      "\u201chow far out are you\u201d, which is a different answer from a "
      "cancellation. Its own row when we get to it.")
    w("- **\u201cYour call showed as spam likely\u201d** \u2014 Carlos's ARS doc has the "
      "answer for this; it is a different trigger from \u201cwhat number will you "
      "call from\u201d and raising spam ourselves puts the word in their head.")
    w("")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT, "·", len(qs), "questions ·",
          sum(len(replies(c, saved)) for c in qs), "replies")


if __name__ == "__main__":
    main()
